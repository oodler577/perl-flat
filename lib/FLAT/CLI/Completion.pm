package FLAT::CLI::Completion;
use strict;
use warnings;
use File::Basename qw(dirname);
use File::Spec;
use File::Path qw(make_path);
use ExtUtils::Packlist;
use FLAT::CLI;

sub bash {
    my ($class) = @_;
    my $meta = FLAT::CLI->completion_metadata;
    my $commands = join ' ', @{$meta->{commands}};
    my $value_options = join '|', @{$meta->{value_options}};
    my $options = join "\n", map {
        "        $_) candidates='" . join(' ', @{$meta->{options}{$_}}) . "' ;;"
    } sort keys %{$meta->{options}};
    my $values = join "\n", map {
        "        $_) candidates='" . join(' ', @{$meta->{values}{$_}}) . "' ;;"
    } sort keys %{$meta->{values}};
    my $file_counts = join "\n", map {
        "            $_) file_count=" . $meta->{file_arguments}{$_} . ' ;;'
    } sort keys %{$meta->{file_arguments}};
    my $script = <<'BASH';
# Generated by fash from its command/option registry. Bash 3.2+.
# Source this file; bash-completion helper functions are not required.
_fash()
{
    local cur="${COMP_WORDS[COMP_CWORD]}" prev='' word command='' expected=''
    local input_format=pre positional=0 options_enabled=1 i option='' prefix=''
    local candidates='' candidate file_count=0
    COMPREPLY=()
    (( COMP_CWORD > 0 )) && prev="${COMP_WORDS[COMP_CWORD-1]}"
    for (( i=1; i<COMP_CWORD; i++ )); do
        word="${COMP_WORDS[i]}"
        if [[ -n $expected ]]; then
            [[ $word == '=' ]] && continue
            [[ $expected == --input-format ]] && input_format="$word"
            expected=''
            continue
        fi
        if (( options_enabled )); then
            case "$word" in
                --) options_enabled=0; continue ;;
                --input-format=*) input_format="${word#*=}"; continue ;;
                __VALUE_OPTIONS__) expected="$word"; continue ;;
                --*=*|-*) continue ;;
            esac
        fi
        if [[ -z $command ]]; then command="$word"; else (( positional++ )); fi
    done
    if (( options_enabled )); then
        if [[ $cur == --*=* ]]; then
            option="${cur%%=*}"; prefix="$option="; cur="${cur#*=}"
        elif [[ $prev == '=' && $COMP_CWORD -gt 1 ]]; then
            option="${COMP_WORDS[COMP_CWORD-2]}"
        elif [[ $cur == '=' && $prev == --* ]]; then
            option="$prev"; cur=''
        else
            option="$expected"
        fi
    fi
    case "$option" in
__VALUES__
        --output)
            while IFS= read -r candidate; do COMPREPLY+=("$prefix$candidate"); done < <(compgen -f -- "$cur")
            compopt -o filenames 2>/dev/null || true
            return ;;
        '') ;;
        *) return ;;
    esac
    if [[ -n $option ]]; then
        while IFS= read -r candidate; do COMPREPLY+=("$prefix$candidate"); done < <(compgen -W "$candidates" -- "$cur")
        return
    fi
    if [[ -z $command || $command == help ]]; then
        if [[ -z $command && $cur == -* ]]; then
            candidates='--help --version'
        else
            candidates='__COMMANDS__'
        fi
    elif [[ $command == completion && $positional == 0 ]]; then
        candidates='bash'
    elif (( options_enabled )) && [[ $cur == -* ]]; then
        case "$command" in
__OPTIONS__
        esac
    elif [[ $input_format == jflap ]]; then
        case "$command" in
__FILE_COUNTS__
        esac
        if (( file_count == -1 || positional < file_count )); then
            while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -f -- "$cur")
            compopt -o filenames 2>/dev/null || true
        fi
        return
    else
        return
    fi
    while IFS= read -r candidate; do COMPREPLY+=("$candidate"); done < <(compgen -W "$candidates" -- "$cur")
}
complete -F _fash fash
BASH
    my %replace = (__COMMANDS__=>$commands, __VALUE_OPTIONS__=>$value_options,
                   __OPTIONS__=>$options, __VALUES__=>$values, __FILE_COUNTS__=>$file_counts);
    $script =~ s/(__[A-Z_]+__)/$replace{$1}/ge;
    return $script;
}

sub install {
    my ($class, %args) = @_;
    return undef if ($args{directory} // '') eq 'none';
    return undef if $^O eq 'MSWin32';
    my $directory;
    if (defined $args{directory} && length $args{directory}) {
        die "completion directory must be absolute\n" unless File::Spec->file_name_is_absolute($args{directory});
        $directory = File::Spec->catdir($args{destdir} // '', $args{directory});
    }
    else {
        die "an installation bin directory is required\n" unless defined $args{bindir} && length $args{bindir};
        $directory = File::Spec->catdir(dirname($args{bindir}), 'share', 'bash-completion', 'completions');
    }
    make_path($directory);
    my $path = File::Spec->catfile($directory, 'fash');
    open my $fh, '>', $path or die "cannot write completion '$path': $!\n";
    print $fh $class->bash or die "cannot write completion '$path': $!\n";
    close $fh or die "cannot close completion '$path': $!\n";
    chmod 0644, $path or die "cannot set completion permissions: $!\n";
    if (defined $args{packlist} && -f $args{packlist}) {
        my $recorded = $path;
        my $destdir = $args{destdir} // '';
        $recorded = substr($recorded, length $destdir)
            if length($destdir) && index($recorded, $destdir . '/') == 0;
        my $packlist = ExtUtils::Packlist->new($args{packlist});
        $packlist->{$recorded} = {type=>'file'};
        $packlist->write;
    }
    return $path;
}
1;

__END__

=head1 NAME

FLAT::CLI::Completion - registry-derived fash Bash completion and installation

=head1 DESCRIPTION

C<bash> returns a Bash 3.2+ completion script generated from the CLI registry.
It completes commands, applicable options, enumerated values and file paths;
it does not evaluate expressions or execute fash during Tab completion.
C<install> is the MakeMaker installation helper. It respects a staged bin
path, optional absolute directory override, DESTDIR and the installation
packlist. See L<perlfash> for user instructions.

=cut
